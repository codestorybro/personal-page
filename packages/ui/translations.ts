const templates = Object.entries(english)
  .filter(([source]) => source.includes('{0}'))
  .map(([source, target]) => {
    const pattern = source
      .split(/(\{\d+\})/)
      .map(part =>
        /^\{\d+\}$/.test(part)
          ? '(.*?)'
          : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'),
      )
      .join('');
    return { pattern: new RegExp(`^${pattern}$`, 's'), target };
  });
export function translate(locale: 'en' | 'pl', text: string): string {
  if (locale === 'pl') {
    return text;
  }
  if (english[text]) {
    return english[text];
  }
  for (const { pattern, target } of templates) {
    const match = text.match(pattern);
    if (match) {
      return target.replace(
        /\{(\d+)\}/g,
        (_, index: string) => match[Number(index) + 1] ?? '',
      );
    }
  }
  return text;
}
